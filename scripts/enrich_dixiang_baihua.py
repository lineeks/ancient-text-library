def process_dir(dirname, mapping, prefix):
    d = os.path.join(BASE, f'library/xiang/dixiang/{dirname}')
    files = sorted([f for f in os.listdir(d) if f.startswith(prefix) and f.endswith('.md')])
    updated = 0
    for fname in files:
        fpath = os.path.join(d, fname)
        text = open(fpath, encoding='utf-8').read()
        m = re.search(r'^### (.+)$', text, re.MULTILINE)
        if not m:
            continue
        title = m.group(1).strip()
        if title not in mapping:
            print(f"  跳过（无白话）: {fname} {title}")
            continue
        new_baihua = mapping[title]
        pattern = r'(\*\*【白话提要】\*\*\n).*?(?=\n*$|\Z)'
        new_text = re.sub(pattern, r'\1' + new_baihua + '\n', text, flags=re.DOTALL)
        if new_text != text:
            with open(fpath, 'w', encoding='utf-8', newline='\n') as f:
                f.write(new_text)
            updated += 1
            print(f"  更新: {fname} {title}")
    return updated, len(files)


