def main():
    # 性命圭旨
    files = sorted([f for f in os.listdir(XMGZ_DIR) if f.startswith('shan6_') and f.endswith('.md')])
    updated = 0
    for fname in files:
        idx = int(fname.split('_')[-1].replace('.md', ''))
        if idx < 0 or idx > 5:
            continue
        fpath = os.path.join(XMGZ_DIR, fname)
        text = open(fpath, encoding='utf-8').read()
        if idx not in XMGZ_BAIHUA:
            continue
        new_baihua = XMGZ_BAIHUA[idx]
        pattern = r'(\*\*【白话提要】\*\*\n).*?(?=\n*$|\Z)'
        new_text = re.sub(pattern, r'\1' + new_baihua + '\n', text, flags=re.DOTALL)
        if new_text != text:
            with open(fpath, 'w', encoding='utf-8', newline='\n') as f:
                f.write(new_text)
            updated += 1
            print(f"  更新性命圭旨: {fname}")
    print(f"性命圭旨白话精译完成: {updated}/6 篇")

    # 太极论
    files = sorted([f for f in os.listdir(TAIJI_DIR) if f.startswith('shan_') and f.endswith('.md')])
    updated = 0
    for fname in files:
        idx = int(fname.split('_')[-1].replace('.md', ''))
        fpath = os.path.join(TAIJI_DIR, fname)
        text = open(fpath, encoding='utf-8').read()
        if idx not in TAIJI_BAIHUA:
            continue
        new_baihua = TAIJI_BAIHUA[idx]
        pattern = r'(\*\*【白话提要】\*\*\n).*?(?=\n*$|\Z)'
        new_text = re.sub(pattern, r'\1' + new_baihua + '\n', text, flags=re.DOTALL)
        if new_text != text:
            with open(fpath, 'w', encoding='utf-8', newline='\n') as f:
                f.write(new_text)
            updated += 1
            print(f"  更新太极论: {fname}")
    print(f"太极论白话精译完成: {updated}/1 篇")


if __name__ == '__main__':
    main()
