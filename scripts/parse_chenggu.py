def fm(id_, section, type_, keywords, weight=2):
    """生成标准 Frontmatter（conditions 八键全空，称骨靠 keywords+type 索引）。"""
    kw = '", "'.join(keywords)
    return f"""---
id: "{id_}"
book: "{BOOK}"
chapter: "{CHAPTER}"
section_title: "{section}"
source_version: "{SOURCE}"
author: "{AUTHOR}"
dynasty: "{DYNASTY}"
type: "{type_}"
conditions:
  day_master: []
  month_branch: []
  day_pillar: []
  hour_pillar: []
  ten_god: []
  pattern: []
  shensha: []
  keywords: ["{kw}"]
weight: {weight}
tags: ["称骨", "袁天罡", "民俗命理"]
---
"""


def write_md(id_, section, type_, keywords, body, weight=2):
    path = os.path.join(OUT_DIR, f"{id_}.md")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(fm(id_, section, type_, keywords, weight))
        f.write(body)
    return path


