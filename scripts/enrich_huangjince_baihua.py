def main():
    files = sorted([f for f in os.listdir(SRC_DIR) if f.endswith('.md') and f != 'INDEX.md'])
    count = 0
    for f in files:
        path = os.path.join(SRC_DIR, f)
        content = open(path, encoding='utf-8').read()

        # 提取section_title
        m = re.search(r'section_title: "(.+?)"', content)
        if not m:
            continue
        title = m.group(1)

        # 找对应的白话
        baihua = BAIHUA.get(title)
        if not baihua:
            print(f'  未找到: {title}')
            continue

        # 替换白话层
        # 找到 **【白话提要】** 之后的内容
        pattern = r'(\*\*【白话提要】\*\*\n).*?(?=\n*$|\Z)'
        new_content = re.sub(pattern, r'\1' + baihua + '\n', content, flags=re.S)

        if new_content != content:
            with open(path, 'w', encoding='utf-8', newline='\n') as fout:
                fout.write(new_content)
            count += 1
            print(f'  已更新: {title}')

    print(f'\n共更新 {count} 条')


if __name__ == '__main__':
    main()
