def write_entry(out_dir, idx, title, content):
    eid = f"xiang6_rzxz_{idx:02d}"
    info = JUAN_INFO.get(title, ("未分类", title, ["地理人子须知"]))
    chapter, section_desc, extra_kws = info
    kws = ["地理人子须知", "人子须知", "相部", "地相", "风水", "堪舆",
           "徐善继", "徐善述", "形峦", title] + extra_kws
    tags = ["相部", "地相", "风水", "地理人子须知", "形峦派"]
    cond_lines = [
        '  day_master: []',
        '  month_branch: []',
        '  day_pillar: []',
        '  hour_pillar: []',
        '  ten_god: []',
        '  pattern: []',
        '  shensha: []',
        f'  keywords: [{", ".join(chr(34)+k+chr(34) for k in kws)}]',
    ]
    cond = "\n".join(cond_lines)
    tags_str = ", ".join(f'"{t}"' for t in tags)
    fm = f"""---
id: "{eid}"
book: "地理人子须知"
chapter: "{chapter}"
section_title: "{title}"
source_version: "中华典藏网（明万历重刊本）"
author: "徐善继、徐善述（江右德行山人，孪生兄弟）"
dynasty: "明"
type: "chapter"
conditions:
{cond}
weight: 4
tags: [{tags_str}]
---
"""
    body = f"### {title}\n\n"
    body += f"**【原文】**\n{content}\n\n"
    baihua = (f"本篇出自《地理人子须知》「{title}」，明徐善继、徐善述孪生兄弟撰，"
              f"全称《重刊人子须知资孝地理心学统宗》，万历年间堪舆集大成巨著，形峦风水教科书级典籍。"
              f"全书8卷，全面系统阐述龙穴砂水四大核心，{section_desc}。"
              f"此书不只是摘抄前人成说，更将作者自己的思考、心得、经验和盘托出，"
              f"考证风水名家历代案例甚多，为古代记载案例最多的堪舆著作，"
              f"形峦家无不推荐，学习龙穴形峦者必读之书。")
    body += f"**【白话提要】**\n{baihua}\n"
    with open(os.path.join(out_dir, f"xiang6_rzxz_{idx:02d}.md"), "w",
              encoding="utf-8", newline="\n") as f:
        f.write(fm + "\n" + body)


def main():
    src = os.path.join(BASE, 'raw/dili-renzi-xuzhi.txt')
    out_dir = os.path.join(BASE, 'library/xiang/dixiang/dili-renzi-xuzhi')
    os.makedirs(out_dir, exist_ok=True)

    text = open(src, encoding='utf-8').read()
    parts = re.split(r'=== (.+?) ===', text)

    idx = 0
    for i in range(1, len(parts), 2):
        title = parts[i].strip()
        content = parts[i + 1].strip() if i + 1 < len(parts) else ""
        if len(content) >= 50:
            write_entry(out_dir, idx, title, content)
            idx += 1

    print(f"  地理人子须知: {idx} 条 → {out_dir}")


if __name__ == '__main__':
    main()
