def main():
    files = sorted([f for f in os.listdir(DIR) if f.startswith('bu4_') and f.endswith('.md')])
    updated = 0
    for fname in files:
        idx = int(fname.split('_')[-1].replace('.md', ''))
        if idx < 62 or idx > 92:
            continue
        fpath = os.path.join(DIR, fname)
        text = open(fpath, encoding='utf-8').read()
        if idx not in BAIHUA:
            print(f"  跳过（无白话）: {fname} idx={idx}")
            continue
        new_baihua = BAIHUA[idx]
        pattern = r'(\*\*【白话提要】\*\*\n).*?(?=\n*$|\Z)'
        new_text = re.sub(pattern, r'\1' + new_baihua + '\n', text, flags=re.DOTALL)
        if new_text != text:
            with open(fpath, 'w', encoding='utf-8', newline='\n') as f:
                f.write(new_text)
            updated += 1
            print(f"  更新: {fname}")
    print(f"\n增删卜易第三批白话精译完成: {updated}/31 篇")


if __name__ == '__main__':
    main()
