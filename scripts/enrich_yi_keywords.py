def enrich_keywords(existing_kws, text):
    """根据正文内容补充分类 keywords，去重，保持顺序。"""
    new_kws = list(existing_kws)
    for kw, triggers in CATEGORY_RULES:
        if kw not in new_kws:
            for trigger in triggers:
                if trigger in text:
                    new_kws.append(kw)
                    break
    return new_kws


def process_file(path):
    """处理单个 md 文件，补充 keywords。"""
    with open(path, encoding="utf-8") as f:
        content = f.read()
    if not content.startswith("---"):
        return False
    end = content.find("\n---", 3)
    if end < 0:
        return False
    fm = content[3:end]
    body = content[end + 4:]
    kw_match = re.search(r"^\s*keywords:\s*\[(.*?)\]\s*$", fm, re.M)
    if not kw_match:
        return False
    existing = re.findall(r'"([^"]+)"', kw_match.group(1))
    new_kws = enrich_keywords(existing, body[:5000])
    if new_kws == existing:
        return False
    new_kw_line = "  keywords: [" + ", ".join(f'"{k}"' for k in new_kws) + "]"
    new_fm = re.sub(r"^\s*keywords:\s*\[.*?\]\s*$", new_kw_line, fm, flags=re.M)
    new_content = "---" + new_fm + "\n---\n" + body
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(new_content)
    return True


