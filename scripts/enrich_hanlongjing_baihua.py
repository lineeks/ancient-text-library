def main():
    files = sorted([f for f in os.listdir(DIR) if f.startswith('xx2_') and f.endswith('.md')])
    updated = 0
    for fname in files:
        fpath = os.path.join(DIR, fname)
        text = open(fpath, encoding='utf-8').read()
        # 提取标题
        m = re.search(r'^### (.+)$', text, re.MULTILINE)
        if not m:
            continue
        title = m.group(1).strip()
        if title not in BAIHUA:
            print(f"  跳过（无白话）: {fname} {title}")
            continue
        # 替换白话层
        new_baihua = BAIHUA[title]
        # 找到【白话提要】层并替换
        pattern = r'(\*\*【白话提要】\*\*\n).*?(?=\n*$|\Z)'
        new_text = re.sub(pattern, r'\1' + new_baihua + '\n', text, flags=re.DOTALL)
        if new_text != text:
            with open(fpath, 'w', encoding='utf-8', newline='\n') as f:
                f.write(new_text)
            updated += 1
            print(f"  更新: {fname} {title}")
    print(f"\n撼龙经白话精译完成: {updated}/{len(files)} 篇")


if __name__ == '__main__':
    main()
